/* ---------------- ГЕНЕРАЦИЯ РАСКЛАДКИ (без пересечений) ----------------
   Мебель ставится «курсором» по комнате: x растёт на ширину + зазор,
   поэтому объекты физически не могут пересечься. Тест это проверяет. */
const FURNITURE = [];
const PICKUPS = [];
const PLATFORMS = [];
const LAMPS = [];
const DECOR = [];
let _fid = 0, _pid = 0, _did = 0;

function furnItem(rm, x, type, loot, extra = {}) {
  const [w, h] = FURN_SIZES[type];
  const fy = FLOORS[rm.f].y;
  const o = Object.assign({
    id: 'f' + (_fid++), type, x, y: fy - h, w, h, loot: loot || ['nothing'],
    floor: rm.f, room: rm.i, opened: false,
  }, extra);
  FURNITURE.push(o);
  return o;
}
/* расставить мебель в комнате с гарантированными зазорами */
function furnish(roomIdx, list, opts = {}) {
  const rm = ROOMS[roomIdx];
  const pad = opts.pad !== undefined ? opts.pad : 90;
  const gap = opts.gap !== undefined ? opts.gap : 62;
  let cursor = rm.x0 + pad;
  const made = [];
  for (const it of list) {
    const [w] = FURN_SIZES[it.type];
    if (cursor + w > rm.x1 - pad) break; // не вылезаем за комнату
    made.push(furnItem(rm, cursor, it.type, it.loot, it.extra));
    cursor += w + gap;
  }
  return made;
}
function addPickup(kind, x, y, floor, room) {
  const o = { id: 'p' + (_pid++), kind, x, y, floor, room, taken: false };
  PICKUPS.push(o);
  return o;
}
/* пикап стоит НА мебели (y чуть выше её верха — не внутри) */
function pickupOn(furn, kind, dx = 0) {
  return addPickup(kind, furn.x + furn.w / 2 + dx, furn.y - 30, furn.floor, furn.room);
}
/* пикап стоит на полу */
function pickupFloor(x, floorIdx, kind) {
  const fy = FLOORS[floorIdx].y;
  const rm = ROOMS.find(r => r.f === floorIdx && x >= r.x0 && x < r.x1);
  return addPickup(kind, x, fy - 26, floorIdx, rm ? rm.i : -1);
}
/* платформа в комнате на высоте h над полом */
function plat(roomIdx, x, above, w, kind = 'one') {
  const rm = ROOMS[roomIdx];
  const y = FLOORS[rm.f].y - above;
  const o = { x, y, w, h: kind === 'solid' ? above : 18, t: kind, room: rm.i, floor: rm.f };
  PLATFORMS.push(o);
  return o;
}
function lamp(roomIdx, x, above, r, on = true, flick = 0.08) {
  const rm = ROOMS[roomIdx];
  const o = { x, y: FLOORS[rm.f].y - above, r, on, flick, floor: rm.f, level: on ? 1 : 0, seed: x * 0.37 };
  LAMPS.push(o);
  return o;
}
function decor(roomIdx, dx, kind) {
  const rm = ROOMS[roomIdx];
  DECOR.push({ room: roomIdx, x: rm.x0 + dx, floor: rm.f, kind, seed: (rm.i * 97 + dx) % 1000 });
}

