const SLABS = [];
(function buildSlabs() {
  const gapsByFloor = {
    1: [[4900, 5100], [5750, 5830], [6200, 6280]], // перекрытие 2 этажа
    2: [[4900, 5100], [6200, 6280]],               // перекрытие 3 этажа
  };
  for (const fi of [1, 2]) {
    const y = FLOORS[fi].y;
    let cursor = 0;
    const gaps = gapsByFloor[fi].slice().sort((a, b) => a[0] - b[0]);
    for (const [g0, g1] of gaps) {
      if (g0 > cursor) SLABS.push({ x: cursor, y, w: g0 - cursor, h: SLAB_H, t: 'solid', kind: 'slab', floor: fi });
      cursor = Math.max(cursor, g1);
    }
    if (cursor < WORLD.w) SLABS.push({ x: cursor, y, w: WORLD.w - cursor, h: SLAB_H, t: 'solid', kind: 'slab', floor: fi });
  }
})();

